"""Generate typed TS wrappers from registered Pydantic bridge contracts."""
from __future__ import annotations

import importlib
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

from .bridge import Bridge


def _identifier(value: str) -> str:
    parts = re.findall(r"[A-Za-z0-9]+", value)
    result = "".join(part[:1].upper() + part[1:] for part in parts)
    if not result or result[0].isdigit():
        result = "Bridge" + result
    return result


def _ts_type(schema: dict[str, Any], defs: dict[str, Any] | None = None,
             seen: frozenset[str] = frozenset()) -> str:
    defs = defs or schema.get("$defs", {})
    if "$ref" in schema:
        ref = schema["$ref"]
        key = ref.removeprefix("#/$defs/").replace("~1", "/").replace("~0", "~")
        if not ref.startswith("#/$defs/") or key not in defs or key in seen:
            return "unknown"
        return _ts_type(defs[key], defs, seen | {key})
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(f"({_ts_type(piece, defs, seen)})" for piece in schema[union])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_ts_type({**schema, "type": one}, defs, seen) for one in kind)
    if kind == "string":
        return "string"
    if kind in ("number", "integer"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{_ts_type(schema.get('items', {}), defs, seen)}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        members = [f"{json.dumps(key, ensure_ascii=False)}{' ' if key in required else '? '}: {_ts_type(value, defs, seen)}"
                   for key, value in properties.items()]
        extra = schema.get("additionalProperties")
        if not members and isinstance(extra, dict):
            return f"Record<string, {_ts_type(extra, defs, seen)}>"
        if not members and extra is True:
            return "Record<string, unknown>"
        return "{ " + "; ".join(members) + " }" if members else "Record<string, never>"
    return "unknown"


def render_bridge_types(bridges: dict[str, Bridge]) -> str:
    lines = ['/** Generated by `pyntral types`. Do not edit. */',
             'import { invokeBridge } from "@pyntral/bridge";', '']
    if any(bridge.upload for bridge in bridges.values()):
        imports = "invokeFileBridge" if all(bridge.upload for bridge in bridges.values()) else "invokeBridge, invokeFileBridge"
        lines[1] = f'import {{ {imports} }} from "@pyntral/bridge";'
    names: set[str] = set()
    for bridge in bridges.values():
        ident = _identifier(bridge.name)
        if ident in names:
            raise ValueError(f"Bridge names produce duplicate TypeScript identifier: {ident}")
        names.add(ident)
        meta = bridge.metadata()
        input_schema = meta["inputSchema"]
        output_schema = meta["outputSchema"]
        file_args = ", file: File, signal?: AbortSignal" if bridge.upload else ""
        invoke = "invokeFileBridge" if bridge.upload else "invokeBridge"
        extra_args = ", file, signal" if bridge.upload else ""
        lines.extend([
            f"export type {ident}Input = {_ts_type(input_schema)};",
            f"export type {ident}Output = {_ts_type(output_schema)};",
            f"export async function {ident[0].lower() + ident[1:]}(input: {ident}Input{file_args}): Promise<{ident}Output> {{",
            f"  return {invoke}<{ident}Input, {ident}Output>({json.dumps(bridge.name)}, input{extra_args});",
            "}", "",
        ])
    if not bridges:
        return "export {}; // No bridges registered yet\n"
    return "\n".join(lines) + "\n"


def _load_env_file(path: Path) -> None:
    if not path.is_file():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key.strip()):
            os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def generate_types(project: Path, app_path: str, *, out: Path | None = None) -> Path:
    project = project.resolve()
    _load_env_file(project / ".env")
    if str(project) not in sys.path:
        sys.path.insert(0, str(project))
    if ":" not in app_path:
        raise ValueError("App must look like module:app")
    module, attribute = app_path.split(":", 1)
    target: Any = importlib.import_module(module)
    for part in attribute.split("."):
        target = getattr(target, part)
    admin = getattr(target.state, "pyntral", None)
    if admin is None:
        raise ValueError("FastAPI app does not have Pyntral mounted")
    destination = project / ".pyntral" / "generated" / "bridges.ts"
    content = render_bridge_types(admin.bridges)
    destinations = [destination]
    if out is not None:
        output = out if out.is_absolute() else project / out
        output = output.resolve()
        if not output.is_relative_to(project):
            raise ValueError("Type output must be inside the project")
        if output not in destinations:
            destinations.append(output)
    for target in destinations:
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
    return destinations[-1]


def configure_editor(project: Path) -> Path:
    """Configure VS Code/tsserver using the managed UI without copying generated sources.

    Never overwrite an existing root tsconfig. That app can extend the generated
    .pyntral/tsconfig.editor.json itself.
    """
    project = project.resolve()
    cache = project / ".pyntral"
    cache.mkdir(parents=True, exist_ok=True)
    config_path = cache / "tsconfig.editor.json"
    aliases = {
        "@pyntral/types": ["./ui/src/types.ts"],
        "@pyntral/api": ["./ui/src/api.ts"],
        "@pyntral/bridge": ["./ui/src/bridge.ts"],
        "@pyntral/generated": ["./generated/bridges.ts"],
        "@pyntral/ui": ["./ui/src/ui.tsx"],
        "@pyntral/auth": ["./ui/src/currentAdmin.tsx"],
        "@pyntral/feedback": ["./ui/src/feedback.tsx"],
        "@pyntral/mutations": ["./ui/src/mutations.ts"],
        "react": ["./ui/node_modules/@types/react/index.d.ts"],
        "react-dom": ["./ui/node_modules/@types/react-dom/index.d.ts"],
        "react/jsx-runtime": ["./ui/node_modules/@types/react/jsx-runtime.d.ts"],
        "lucide-react": ["./ui/node_modules/lucide-react"],
        "@tanstack/react-query": ["./ui/node_modules/@tanstack/react-query"],
    }
    include = ["../admin/**/*.ts", "../admin/**/*.tsx", "./generated/**/*.ts"]
    components = project / "pyntral.components.json"
    if components.is_file():
        cfg = json.loads(components.read_text(encoding="utf-8"))
        for group in ("fields", "pages", "actions", "dialogs", "crud", "themes", "profile", "access", "auth", "sidebarHeaders", "sidebarFooters", "sidebarItems"):
            for name in cfg.get(group, {}).values():
                source = (project / name).resolve()
                if not source.is_relative_to(project):
                    raise ValueError("Extension outside project")
                relative = "../" + source.relative_to(project).as_posix()
                if relative not in include:
                    include.append(relative)
    config = {
        "compilerOptions": {
            "target": "ES2022", "lib": ["ES2022", "DOM", "DOM.Iterable"],
            "module": "ESNext", "moduleResolution": "Bundler", "jsx": "react-jsx",
            "strict": True, "noEmit": True, "skipLibCheck": True,
            "baseUrl": ".", "types": [], "paths": aliases,
        },
        "include": include,
    }
    contents = json.dumps(config, indent=2) + "\n"
    if not config_path.exists() or config_path.read_text(encoding="utf-8") != contents:
        config_path.write_text(contents, encoding="utf-8")
    root_config = project / "tsconfig.json"
    if not root_config.exists():
        root_config.write_text(json.dumps({"extends": "./.pyntral/tsconfig.editor.json"}, indent=2) + "\n", encoding="utf-8")
    return root_config
