/** A complete CRUD list override; built-in create/edit/show routes still work. */
import { useEffect, useRef, useState } from "react";
import type { CustomCrudProps, RecordData } from "@pyntral/types";

export default function TagCatalog({ resource, loadList, navigate }: CustomCrudProps) {
  // The generic CRUD renderer supplies a new loadList function on each render.
  // Keep its current implementation without refetching on each rerender.
  const loadListRef = useRef(loadList);
  loadListRef.current = loadList;
  const [items, setItems] = useState<RecordData[]>([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    setLoading(true);
    loadListRef.current({ limit: 100, sort: "name" })
      .then((page) => {
        if (!cancelled) {
          setItems(page.items);
          setTotal(page.total);
          setError(null);
        }
      })
      .catch((reason: unknown) => {
        if (!cancelled) setError(reason instanceof Error ? reason.message : "Unable to load tags");
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => { cancelled = true; };
  }, [resource.id]);

  return <section aria-label="Custom tag catalog">
    <header className="page-heading">
      <div>
        <div className="eyebrow">CUSTOM CRUD LIST</div>
        <h1>Tags</h1>
        <p>This page is a registered TSX override. Other CRUD screens are generated by Pyntral.</p>
      </div>
      {resource.capabilities.create &&
        <button className="btn primary" type="button" onClick={() => navigate("resources/" + resource.id + "/new")}>
          New tag
        </button>}
    </header>
    {loading ? <p role="status">Loading tags…</p> : error ? <p role="alert">{error}</p> :
      <div className="surface" style={{ padding: 18 }}>
        <p style={{ color: "var(--ra-text-secondary)" }}>{total} tags · Custom view</p>
        <ul style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(190px, 1fr))", gap: 12,
          listStyle: "none", padding: 0, margin: 0 }}>
          {items.map((tag) => {
            const id = String(tag[resource.primaryKey]);
            const color = typeof tag.color === "string" && /^#[0-9a-fA-F]{6}$/.test(tag.color)
              ? tag.color : "var(--ra-primary)";
            return <li key={id}>
              <button type="button" className="resource-card" style={{ width: "100%" }}
                onClick={() => navigate("resources/" + resource.id + "/" + encodeURIComponent(id))}>
                <span aria-hidden="true" style={{ background: color, width: 13, height: 13,
                  borderRadius: 4, flexShrink: 0 }} />
                <strong>{String(tag.name ?? ("Tag #" + id))}</strong>
              </button>
            </li>;
          })}
        </ul>
        {items.length === 0 && <p>No tags yet. Create one to try the custom CRUD list.</p>}
      </div>}
  </section>;
}
